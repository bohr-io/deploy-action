import { readFileSync } from 'node:fs';
import { relative } from 'node:path';
import { type BundleOptions, bundleWorker, type WorkerBundle } from './bundle';
import { locateConfig, parseConfig } from './config';
import { errorMessage, type Fetch, type Sleep } from './http';
import {
  type AssetsConfig,
  createDeploySession,
  type FinalizeMetadata,
  finalizeDeployment,
  type InstanceClient,
  normalizeInstanceUrl,
} from './instance';
import { formatBytes, type Logger, plural, printable } from './log';
import { type AssetsBuild, buildAssetManifest } from './manifest';
import { decodeJwtPayload, uploadAssets } from './upload';

/** Audience the instance expects in the GitHub OIDC token. */
export const OIDC_AUDIENCE = 'bohr.io';
/** A token closer than this to its expiry is replaced before the next instance call. */
const TOKEN_REFRESH_MARGIN_MS = 60_000;
/** Most uploaded paths listed in the log, as wrangler does. */
const MAX_LISTED_UPLOADS = 100;
/** Largest _redirects or _headers file the instance accepts. */
const MAX_ROUTING_FILE_SIZE = 256 * 1024;

export interface DeployOptions {
  /** Absolute path of the folder with the wrangler config. */
  workingDirectory: string;
  instanceUrl: string;
  commitSha: string | null;
}

export interface DeployDependencies {
  fetch: Fetch;
  /** Returns a GitHub OIDC token with audience bohr.io. */
  getIdToken: () => Promise<string>;
  logger: Logger;
  bundleWorker?: (options: BundleOptions) => Promise<WorkerBundle>;
  sleep?: Sleep;
  now?: () => number;
}

export interface DeployResult {
  deploymentId: string;
  script: string;
  url: string;
  mainModule: string | null;
  modules: number;
  assetFiles: number;
  assetBytes: number;
  uploadedFiles: number;
  uploadedBytes: number;
}

/** Runs the whole deploy: config, bundle, assets manifest, session, uploads, finalize. */
export async function deploy(options: DeployOptions, deps: DeployDependencies): Promise<DeployResult> {
  const { logger } = deps;
  const instanceUrl = normalizeInstanceUrl(options.instanceUrl);
  const shown = (path: string) => relative(process.cwd(), path).replaceAll('\\', '/') || '.';
  const idToken = oidcTokens(deps.getIdToken, logger, deps.now ?? Date.now);

  // Fail fast when the workflow lacks `id-token: write`.
  await logger.group('Request GitHub OIDC token', async () => {
    await idToken();
    logger.info(`Got a token for audience ${OIDC_AUDIENCE}.`);
  });

  const config = await logger.group('Read wrangler config', async () => {
    const location = locateConfig(options.workingDirectory);
    if (location.redirected) {
      logger.info(`Using ${shown(location.path)}, the config generated by the build (.wrangler/deploy/config.json).`);
    }
    const parsed = parseConfig(readFileSync(location.path, 'utf8'), location.path);
    logger.info(`Config: ${shown(parsed.configPath)}`);
    logger.info(`Worker entry: ${parsed.main ? shown(parsed.main) : 'none (static assets only)'}`);
    logger.info(`Assets directory: ${parsed.assets ? shown(parsed.assets.directory) : 'none'}`);
    const flags = parsed.compatibilityFlags.length > 0 ? ` (${parsed.compatibilityFlags.join(', ')})` : '';
    logger.info(`Compatibility date: ${parsed.compatibilityDate}${flags}`);
    for (const warning of parsed.warnings) logger.warning(warning);
    return parsed;
  });

  let bundle: WorkerBundle | null = null;
  const main = config.main;
  if (main) {
    bundle = await logger.group('Bundle the Worker with wrangler', async () => {
      const result = await (deps.bundleWorker ?? bundleWorker)({
        workingDirectory: options.workingDirectory,
        configPath: config.configPath,
        main,
        workerName: config.name,
        log: (message) => logger.info(message),
      });
      const bytes = result.modules.reduce((total, module) => total + module.content.byteLength, 0);
      logger.info(
        `Main module ${result.mainModule}; ${plural(result.modules.length, 'module')}, ${formatBytes(bytes)}:`,
      );
      for (const module of result.modules) logger.info(`  ${printable(module.name)} (${module.contentType})`);
      return result;
    });
  }

  let assets: AssetsBuild | null = null;
  const assetsDirectory = config.assets?.directory;
  if (assetsDirectory) {
    assets = await logger.group('Hash static assets', async () => {
      const result = await buildAssetManifest(assetsDirectory);
      for (const warning of result.warnings) logger.warning(warning);
      if (result.files.length === 0) {
        logger.warning(`The assets directory ${shown(assetsDirectory)} has no files to deploy. Did the build run?`);
      }
      logger.info(
        `${plural(result.files.length, 'file')}, ${formatBytes(result.totalBytes)} in ${shown(assetsDirectory)}.`,
      );
      return result;
    });
  }
  if (!bundle && !assets?.files.length) {
    throw new Error(
      `Nothing to deploy: the assets directory ${shown(assetsDirectory ?? '.')} is empty and the wrangler config has no main.`,
    );
  }

  const client = async (): Promise<InstanceClient> => ({
    instanceUrl,
    token: await idToken(),
    fetch: deps.fetch,
    sleep: deps.sleep,
    log: (message) => logger.info(message),
  });

  const session = await logger.group('Open deploy session', async () => {
    const assetsConfig: AssetsConfig = {};
    if (config.assets?.notFoundHandling) assetsConfig.notFoundHandling = config.assets.notFoundHandling;
    if (config.assets?.htmlHandling) assetsConfig.htmlHandling = config.assets.htmlHandling;
    if (config.assets?.runWorkerFirst !== undefined) assetsConfig.runWorkerFirst = config.assets.runWorkerFirst;
    for (const [name, contents] of [
      ['_redirects', assets?.redirects],
      ['_headers', assets?.headers],
    ] as const) {
      if (contents === undefined) continue;
      if (Buffer.byteLength(contents) > MAX_ROUTING_FILE_SIZE) {
        throw new Error(
          `${name} is ${formatBytes(Buffer.byteLength(contents))}; bohr.io Cloud accepts up to ${formatBytes(MAX_ROUTING_FILE_SIZE)}.`,
        );
      }
      if (name === '_redirects') assetsConfig.redirects = contents;
      else assetsConfig.headers = contents;
      logger.info(`Applying ${name} from ${shown(assetsDirectory ?? '.')}.`);
    }
    const result = await createDeploySession(await client(), { manifest: assets?.manifest ?? {}, assetsConfig });
    if (result.uploadToken) logger.setSecret(result.uploadToken);
    logger.info(`Session ${result.sessionId} on ${instanceUrl}.`);
    return result;
  });

  const pending = session.buckets.flat();
  let completionToken = session.uploadToken;
  let uploadedFiles = 0;
  let uploadedBytes = 0;
  if (pending.length > 0) {
    const { uploadToken, accountId } = session;
    if (!assets || !uploadToken || !accountId) {
      throw new Error(
        'The bohr instance asked for asset uploads without an upload token and account. Check instance-url.',
      );
    }
    const result = await logger.group(`Upload ${plural(pending.length, 'new or changed asset')}`, async () => {
      const byHash = new Map(assets.files.map((file) => [file.hash, file.path]));
      for (const hash of pending.slice(0, MAX_LISTED_UPLOADS)) logger.info(`+ ${printable(byHash.get(hash) ?? hash)}`);
      if (pending.length > MAX_LISTED_UPLOADS) logger.info(`  (and ${pending.length - MAX_LISTED_UPLOADS} more)`);
      return uploadAssets({
        accountId,
        uploadToken,
        buckets: session.buckets,
        files: assets.files,
        fetch: deps.fetch,
        sleep: deps.sleep,
        log: (message) => logger.info(message),
      });
    });
    logger.setSecret(result.completionToken);
    completionToken = result.completionToken;
    uploadedFiles = result.uploadedFiles;
    uploadedBytes = result.uploadedBytes;
  } else if (assets?.files.length) {
    logger.info('No new or changed assets: Cloudflare already stores every file.');
  }
  if (assets?.files.length && !completionToken) {
    throw new Error('The bohr instance did not return an assets upload token. Check instance-url.');
  }

  const deployment = await logger.group('Finalize deployment', async () => {
    const metadata: FinalizeMetadata = {
      mainModule: bundle?.mainModule ?? null,
      compatibilityDate: config.compatibilityDate,
      compatibilityFlags: config.compatibilityFlags,
      vars: config.vars,
      assetsBinding: completionToken ? (config.assets?.binding ?? null) : null,
      assetsCompletionToken: completionToken,
      commitSha: options.commitSha,
    };
    const result = await finalizeDeployment(await client(), session.sessionId, metadata, bundle?.modules ?? []);
    logger.info(`Deployed ${result.url} (deployment ${result.deploymentId}, script ${result.script}).`);
    return result;
  });

  return {
    ...deployment,
    mainModule: bundle?.mainModule ?? null,
    modules: bundle?.modules.length ?? 0,
    assetFiles: assets?.files.length ?? 0,
    assetBytes: assets?.totalBytes ?? 0,
    uploadedFiles,
    uploadedBytes,
  };
}

/** Caches the OIDC token and requests a fresh one when it is about to expire. */
function oidcTokens(getIdToken: () => Promise<string>, logger: Logger, now: () => number): () => Promise<string> {
  let token: string | undefined;
  return async () => {
    if (token) {
      const exp = decodeJwtPayload(token)?.exp;
      if (typeof exp !== 'number' || exp * 1000 - now() > TOKEN_REFRESH_MARGIN_MS) return token;
      logger.info('The GitHub OIDC token is about to expire; requesting a new one.');
    }
    try {
      token = await getIdToken();
    } catch (error) {
      const reason = errorMessage(error)
        .replace(/^Error message:\s*/, '')
        .replace(/\s+/g, ' ')
        .trim();
      throw new Error(
        `Could not get a GitHub OIDC token: ${reason}. The workflow (or job) needs "permissions: id-token: write"; see the action's README.`,
      );
    }
    logger.setSecret(token);
    return token;
  };
}
